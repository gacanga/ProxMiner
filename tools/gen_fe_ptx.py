#!/usr/bin/env python3
"""ProxMiner - generates gpu/fe_ptx.h: GF(2^255-19) arithmetic in inline PTX with carry chains
(8 x 32-bit limbs, values below 2^256), used on the GPU instead of the portable C of px_core.h.
  python3 tools/gen_fe_ptx.py > gpu/fe_ptx.h"""

def asm_block(lines, outs, ins, name):
    """outs/ins: lists of (constraint, expr)"""
    body = "\n".join('\t\t"%s\\n\\t"' % l for l in lines)
    o = ", ".join('"%s"(%s)' % c for c in outs)
    i = ", ".join('"%s"(%s)' % c for c in ins)
    return '\tasm(\n%s\n\t\t: %s\n\t\t: %s);\n' % (body, o, i)

def reg(n): return "%%%d" % n

def mul_lines(a, b, r):
    """a, b: operand register indexes (8 each), r: 16 result register indexes"""
    L = []
    # row 0
    L.append("mul.lo.u32 %s, %s, %s;" % (r[0], a[0], b[0]))
    L.append("mul.hi.u32 %s, %s, %s;" % (r[1], a[0], b[0]))
    for j in range(1, 8):
        L.append("mad.lo.cc.u32 %s, %s, %s, %s;" % (r[j], a[0], b[j], r[j]))
        L.append("madc.hi.u32 %s, %s, %s, 0;" % (r[j + 1], a[0], b[j]))
    for i in range(1, 8):
        L.append("mad.lo.cc.u32 %s, %s, %s, %s;" % (r[i], a[i], b[0], r[i]))
        for j in range(1, 8):
            L.append("madc.lo.cc.u32 %s, %s, %s, %s;" % (r[i + j], a[i], b[j], r[i + j]))
        L.append("addc.u32 %s, 0, 0;" % r[i + 8])
        L.append("mad.hi.cc.u32 %s, %s, %s, %s;" % (r[i + 1], a[i], b[0], r[i + 1]))
        for j in range(1, 7):
            L.append("madc.hi.cc.u32 %s, %s, %s, %s;" % (r[i + j + 1], a[i], b[j], r[i + j + 1]))
        L.append("madc.hi.u32 %s, %s, %s, %s;" % (r[i + 8], a[i], b[7], r[i + 8]))
    return L

def sq_lines(a, r):
    L = []
    # cross products a_i a_j, i < j, into r[1..14]; r[0] = 0, r[15] = 0 before doubling
    # row 0: a0 * a1..a7 -> r1..r8
    L.append("mul.lo.u32 %s, %s, %s;" % (r[1], a[0], a[1]))
    L.append("mul.hi.u32 %s, %s, %s;" % (r[2], a[0], a[1]))
    for j in range(2, 8):
        L.append("mad.lo.cc.u32 %s, %s, %s, %s;" % (r[j], a[0], a[j], r[j]))
        L.append("madc.hi.u32 %s, %s, %s, 0;" % (r[j + 1], a[0], a[j]))
    for i in range(1, 7):
        js = list(range(i + 1, 8))
        # lo chain: positions i+j
        first = True
        for j in js:
            op = "mad.lo.cc.u32" if first else "madc.lo.cc.u32"
            L.append("%s %s, %s, %s, %s;" % (op, r[i + j], a[i], a[j], r[i + j]))
            first = False
        L.append("addc.u32 %s, 0, 0;" % r[i + 8])
        # hi chain: positions i+j+1
        for n, j in enumerate(js):
            last = n == len(js) - 1
            if n == 0 and last:
                op = "mad.hi.u32"
            elif n == 0:
                op = "mad.hi.cc.u32"
            elif last:
                op = "madc.hi.u32"
            else:
                op = "madc.hi.cc.u32"
            L.append("%s %s, %s, %s, %s;" % (op, r[i + j + 1], a[i], a[j], r[i + j + 1]))
    # double r[1..14] -> r[1..15]
    L.append("add.cc.u32 %s, %s, %s;" % (r[1], r[1], r[1]))
    for k in range(2, 15):
        L.append("addc.cc.u32 %s, %s, %s;" % (r[k], r[k], r[k]))
    L.append("addc.u32 %s, 0, 0;" % r[15])
    # squares
    L.append("mul.lo.u32 %s, %s, %s;" % (r[0], a[0], a[0]))
    L.append("mad.hi.cc.u32 %s, %s, %s, %s;" % (r[1], a[0], a[0], r[1]))
    for i in range(1, 8):
        L.append("madc.lo.cc.u32 %s, %s, %s, %s;" % (r[2 * i], a[i], a[i], r[2 * i]))
        op = "madc.hi.cc.u32" if i < 7 else "madc.hi.u32"
        L.append("%s %s, %s, %s, %s;" % (op, r[2 * i + 1], a[i], a[i], r[2 * i + 1]))
    return L

def reduce_lines(t, out, c, c2):
    """t: 16 regs (lo = t[0..7], hi = t[8..15]) -> out (8 regs) = lo + 38 hi mod 2^256 folded"""
    L = []
    h = t[8:]; l = t[:8]
    L.append("mad.lo.cc.u32 %s, %s, 38, %s;" % (out[0], h[0], l[0]))
    for j in range(1, 8):
        L.append("madc.lo.cc.u32 %s, %s, 38, %s;" % (out[j], h[j], l[j]))
    L.append("addc.u32 %s, 0, 0;" % c)
    L.append("mad.hi.cc.u32 %s, %s, 38, %s;" % (out[1], h[0], out[1]))
    for j in range(1, 7):
        L.append("madc.hi.cc.u32 %s, %s, 38, %s;" % (out[j + 1], h[j], out[j + 1]))
    L.append("madc.hi.u32 %s, %s, 38, %s;" % (c, h[7], c))
    # out + 38 c
    L.append("mad.lo.cc.u32 %s, %s, 38, %s;" % (out[0], c, out[0]))
    for j in range(1, 8):
        L.append("addc.cc.u32 %s, %s, 0;" % (out[j], out[j]))
    L.append("addc.u32 %s, 0, 0;" % c2)
    L.append("mad.lo.u32 %s, %s, 38, %s;" % (out[0], c2, out[0]))
    return L

def gen():
    print("/* generated by tools/gen_fe_ptx.py - do not edit */")
    print("#pragma once")
    print("")
    # fe_mul: operands %0..%7 out, %8..%15 a, %16..%23 b ; temps declared inside
    out = [reg(i) for i in range(8)]
    a = [reg(8 + i) for i in range(8)]
    b = [reg(16 + i) for i in range(8)]
    t = ["t%d" % i for i in range(16)]
    lines = ["{", ".reg .u32 " + ", ".join(t) + ", c, c2;"]
    lines += mul_lines(a, b, t)
    lines += reduce_lines(t, out, "c", "c2")
    lines.append("}")
    print("__device__ __forceinline__ void fe_mul_ptx(fe &r, const fe &a, const fe &b)\n{")
    print(asm_block(lines, [("=r", "r.v[%d]" % i) for i in range(8)],
                    [("r", "a.v[%d]" % i) for i in range(8)] + [("r", "b.v[%d]" % i) for i in range(8)], "mul"), end="")
    print("}\n")
    a = [reg(8 + i) for i in range(8)]
    lines = ["{", ".reg .u32 " + ", ".join(t) + ", c, c2;"]
    lines += sq_lines(a, t)
    lines += reduce_lines(t, out, "c", "c2")
    lines.append("}")
    print("__device__ __forceinline__ void fe_sq_ptx(fe &r, const fe &a)\n{")
    print(asm_block(lines, [("=r", "r.v[%d]" % i) for i in range(8)], [("r", "a.v[%d]" % i) for i in range(8)], "sq"), end="")
    print("}\n")
    # fe_add: r = a + b, fold carry twice
    lines = ["{", ".reg .u32 c, s0, s1, s2, s3, s4, s5, s6, s7;"]
    lines.append("add.cc.u32 s0, %8, %16;")
    for i in range(1, 8):
        lines.append("addc.cc.u32 s%d, %%%d, %%%d;" % (i, 8 + i, 16 + i))
    lines.append("addc.u32 c, 0, 0;")
    lines.append("mad.lo.cc.u32 s0, c, 38, s0;")
    for i in range(1, 8):
        lines.append("addc.cc.u32 s%d, s%d, 0;" % (i, i))
    lines.append("addc.u32 c, 0, 0;")
    lines.append("mad.lo.u32 %0, c, 38, s0;")
    for i in range(1, 8):
        lines.append("mov.u32 %%%d, s%d;" % (i, i))
    lines.append("}")
    print("__device__ __forceinline__ void fe_add_ptx(fe &r, const fe &a, const fe &b)\n{")
    print(asm_block(lines, [("=r", "r.v[%d]" % i) for i in range(8)],
                    [("r", "a.v[%d]" % i) for i in range(8)] + [("r", "b.v[%d]" % i) for i in range(8)], "add"), end="")
    print("}\n")
    # fe_sub: r = a - b, borrow -> subtract 38, twice
    lines = ["{", ".reg .u32 m, s0, s1, s2, s3, s4, s5, s6, s7;"]
    lines.append("sub.cc.u32 s0, %8, %16;")
    for i in range(1, 8):
        lines.append("subc.cc.u32 s%d, %%%d, %%%d;" % (i, 8 + i, 16 + i))
    lines.append("subc.u32 m, 0, 0;")          # 0 or 0xffffffff
    lines.append("and.b32 m, m, 38;")
    lines.append("sub.cc.u32 s0, s0, m;")
    for i in range(1, 8):
        lines.append("subc.cc.u32 s%d, s%d, 0;" % (i, i))
    lines.append("subc.u32 m, 0, 0;")
    lines.append("and.b32 m, m, 38;")
    lines.append("sub.u32 %0, s0, m;")
    for i in range(1, 8):
        lines.append("mov.u32 %%%d, s%d;" % (i, i))
    lines.append("}")
    print("__device__ __forceinline__ void fe_sub_ptx(fe &r, const fe &a, const fe &b)\n{")
    print(asm_block(lines, [("=r", "r.v[%d]" % i) for i in range(8)],
                    [("r", "a.v[%d]" % i) for i in range(8)] + [("r", "b.v[%d]" % i) for i in range(8)], "sub"), end="")
    print("}\n")

if __name__ == "__main__":
    gen()
